'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium}=require('playwright');
const args=process.argv.slice(2);
const option=name=>args[args.indexOf(name)+1];
const state=JSON.parse(fs.readFileSync(option('--state'),'utf8')),output=option('--output');
fs.mkdirSync(output,{recursive:true});
const report={checks:[],errors:[]};
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
  async function login(js=true){
   const ctx=await browser.newContext({viewport:{width:1440,height:1000},javaScriptEnabled:js});const page=await ctx.newPage();
   page.on('pageerror',e=>report.errors.push(e.message));
   await page.goto(state.web_url+'/login');await page.locator('#login_email').fill('operator1');await page.locator('#password').fill(state.password);
   await Promise.all([page.waitForURL('**/panel'),page.locator('button[type=submit]').click()]);return {ctx,page};
  }
  const {ctx,page}=await login();await page.goto(state.web_url+'/inventario',{waitUntil:'networkidle'});
  assert.equal(await page.getByRole('button',{name:'Filtrar',exact:true}).isVisible(),false);
  assert.equal(await page.getByRole('button',{name:'Aplicar horario',exact:true}).isVisible(),false);
  assert.ok(!(await page.locator('body').innerText()).includes('Entorno de pruebas'));
  assert.equal(await page.locator('.workspace-footer').count(),0);
  await page.evaluate(()=>window.controlsCheck='same-document');
  await page.locator('#filter-q').fill('SAN-NL-');
  await page.waitForFunction(()=>new URL(location.href).searchParams.get('q')==='SAN-NL-');
  const first=await page.locator('tbody tr').first().innerText();
  await page.locator('[data-page-next]').first().click();
  await page.waitForFunction(()=>document.querySelector('[data-filter-results]').dataset.page==='2');
  assert.notEqual(await page.locator('tbody tr').first().innerText(),first);
  assert.equal(new URL(page.url()).searchParams.get('q'),'SAN-NL-');
  assert.equal(await page.locator('[data-page-next]').count(),0);
  await page.locator('[data-page-previous]').first().click();
  await page.waitForFunction(()=>document.querySelector('[data-filter-results]').dataset.page==='1');
  assert.equal(await page.evaluate(()=>window.controlsCheck),'same-document');
  report.checks.push('Filtros automáticos sin botón; paginación Anterior/Siguiente real, sin recarga, conserva búsqueda y límites');
  const zone=page.locator('#display-timezone'), original=await zone.inputValue();const target=original==='UTC'?'America/Monterrey':'UTC';
  const before=await page.locator('time[data-local-time]').first().innerText();
  await zone.selectOption(target);await page.waitForFunction(z=>document.querySelector('.timezone-picker input[name="_timezone"]').value===z,target);
  assert.notEqual(await page.locator('time[data-local-time]').first().innerText(),before);
  assert.equal(await page.evaluate(()=>window.controlsCheck),'same-document');
  await page.locator('[data-record-view]').first().click();await page.locator('[data-detail-content]').waitFor();
  assert.ok(await page.locator('#record-dialog-body time[data-local-time]').count());await page.keyboard.press('Escape');
  await page.screenshot({path:path.join(output,'controls-desktop.png')});
  await page.setViewportSize({width:390,height:1000});
  await page.waitForFunction(()=>document.querySelector('#sidebar').getBoundingClientRect().right<=1);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.ok(await page.locator('.page-heading > div').evaluate(e=>e.getBoundingClientRect().right<=innerWidth),'Encabezado fuera del ancho móvil');
  await page.screenshot({path:path.join(output,'controls-mobile.png')});
  report.checks.push('Horario automático actualiza fechas y modales; controles visibles y sin desbordamiento en 390 px');
  await page.goto(state.web_url+'/inventario/nuevo');
  assert.equal(await zone.inputValue(),target);
  await page.locator('#folio').fill('BORRADOR-NO-GUARDADO');await page.locator('#expires_at').fill('2026-10-20T12:30');
  const change=page.waitForResponse(r=>r.url().endsWith('/preferencias/horario'));
  await zone.selectOption(original);assert.equal((await change).status(),200);
  await page.waitForFunction(z=>document.querySelector('.record-form input[name="_timezone"]').value===z,original);
  const expected=target==='UTC'?'2026-10-20T06:30':'2026-10-20T18:30';
  assert.equal(await page.locator('#expires_at').inputValue(),expected);
  assert.equal(await page.locator('#folio').inputValue(),'BORRADOR-NO-GUARDADO');
  assert.equal(await page.locator('#expires_at').isDisabled(),false);
  await page.route('**/preferencias/horario',route=>route.fulfill({status:503,body:'Temporary'}));
  await zone.selectOption(target);await page.getByText('No se pudo cambiar el horario.',{exact:false}).waitFor();
  assert.equal(await zone.inputValue(),original);assert.equal(await page.locator('#expires_at').inputValue(),expected);
  assert.equal(await page.locator('#expires_at').isDisabled(),false);
  report.checks.push('Zona persiste; formulario conserva borrador e instante de fecha; 503 revierte selector sin perder datos');
  await ctx.close();
  const fallback=await login(false);await fallback.page.goto(state.web_url+'/inventario');
  assert.equal(await fallback.page.getByRole('button',{name:'Filtrar',exact:true}).isVisible(),true);
  await fallback.page.locator('[data-page-next]').first().click();assert.equal(new URL(fallback.page.url()).searchParams.get('page'),'2');
  report.checks.push('Sin JavaScript: filtro manual y enlaces de paginación siguen operativos');await fallback.ctx.close();
  assert.deepEqual(report.errors,[]);report.result='passed';
 }finally{await browser.close();fs.writeFileSync(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n');}
 console.log(JSON.stringify(report));
})().catch(e=>{console.error(e.stack);process.exitCode=1;});
